import { chromium } from "@playwright/test";
const BASE = "http://localhost:3200";
const login = await fetch(`${BASE}/api/auth/login`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ email: "dana@demo.test", password: "demo-password-123" }) });
const [name, ...rest] = login.headers.get("set-cookie").split(";")[0].split("=");
const ws = (await (await fetch(`${BASE}/api/workspaces`, { headers: { cookie: `${name}=${rest.join("=")}` } })).json()).data.documents.find((w) => w.name === "Demo Studio").$id;
const browser = await chromium.launch({ executablePath: "/usr/bin/chromium", args: ["--no-sandbox"] });
const context = await browser.newContext();
await context.addCookies([{ name, value: rest.join("="), url: BASE, httpOnly: true, secure: true }]);
const page = await context.newPage();
const cdp = await context.newCDPSession(page);
await cdp.send("Network.enable");
const reqs = new Map();
cdp.on("Network.responseReceived", (e) => reqs.set(e.requestId, { url: e.response.url, type: e.type }));
const done = [];
cdp.on("Network.loadingFinished", (e) => { const r = reqs.get(e.requestId); if (r) done.push({ ...r, bytes: e.encodedDataLength }); });
await page.goto(`${BASE}/workspaces/${ws}`);
await page.getByText("Overdue").first().waitFor({ state: "visible" });
const beforeVisible = done.filter((d) => d.type === "Script");
await page.waitForTimeout(2500);
const kbList = (l) => Math.round(l.reduce((n, d) => n + d.bytes, 0) / 1024);
console.log(`needed before the page showed: ${beforeVisible.length} scripts, ${kbList(beforeVisible)} KB`);
for (const d of [...beforeVisible].sort((a, b) => b.bytes - a.bytes).slice(0, 8)) console.log("  ", String(Math.round(d.bytes / 1024)).padStart(4), "KB", d.url.replace(BASE + "/_next/static/chunks/", ""));
const scripts = done.filter((d) => d.type === "Script");
const css = done.filter((d) => d.type === "Stylesheet");
const fonts = done.filter((d) => d.type === "Font");
const kb = (list) => Math.round(list.reduce((n, d) => n + d.bytes, 0) / 1024);
console.log(`scripts: ${scripts.length} files, ${kb(scripts)} KB transferred · css: ${css.length} files, ${kb(css)} KB · fonts: ${fonts.length}, ${kb(fonts)} KB`);
for (const d of scripts.sort((a, b) => b.bytes - a.bytes).slice(0, 10)) console.log(String(Math.round(d.bytes / 1024)).padStart(5), "KB", d.url.replace(BASE + "/_next/static/", ""));
await browser.close();
